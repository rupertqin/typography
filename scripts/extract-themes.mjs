#!/usr/bin/env node
/**
 * 从原站 Typeset chunk 中切出「主题套件」区块，生成 src/lib/themes.generated.js。
 *
 * 原包（reference/Typeset.chunk.js）是 Vite 压缩产物，主题、装饰函数、代码高亮
 * 调色板全部内联。主题的 decor 里含函数（h1/h2/h3/ulMark/olMark/hr/card/quoteMark），
 * 因此不能 JSON 化，只能原样切片保留可执行源码。
 *
 * 切片区间（字符偏移，随原包版本变化，运行时用锚点重新定位）：
 *   起点：`function Te(`            —— hex → rgba helper，其后紧跟 Re/ue/Y 字体常量
 *   终点：第 35 个主题对象后的 `];`  —— `const Me=[...]`
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHUNK = resolve(ROOT, 'reference/Typeset.chunk.js');
const OUT = resolve(ROOT, 'src/lib/themes.generated.js');

const THEME_HEAD = /\{id:"([a-z0-9-]+)",name:"([^"]+)",accent:"#/g;

function locate(chunk) {
  const start = chunk.indexOf('function Te(');
  if (start < 0) throw new Error('定位失败：未找到 "function Te("，原包结构可能已变化');

  const heads = [...chunk.matchAll(THEME_HEAD)];
  if (heads.length !== 35) {
    throw new Error(`主题数量异常：期望 35，实际 ${heads.length}`);
  }

  const last = heads[heads.length - 1];
  const end = chunk.indexOf('];', last.index);
  if (end < 0) throw new Error('定位失败：主题数组未闭合');

  return {
    start,
    end: end + 2,
    ids: heads.map((m) => m[1]),
    names: heads.map((m) => m[2]),
  };
}

const chunk = readFileSync(CHUNK, 'utf8');
const { start, end, ids, names } = locate(chunk);
const body = chunk.slice(start, end);

// 基本完整性校验：切片内必须能数到同样的 35 个主题头
const inside = [...body.matchAll(THEME_HEAD)].length;
if (inside !== 35) throw new Error(`切片不完整：切片内主题数 ${inside}`);

const banner = `// @generated by scripts/extract-themes.mjs — 请勿手改
// 源码：原站 /assets/Typeset-3PJF3xUw.js（见 reference/README.md）
// 内容：字体常量 + 代码高亮明暗调色板 + 装饰 helper + L() 主题工厂 + 35 套主题
// 切片偏移：${start} – ${end}（${end - start} 字符）
`;

const footer = `
export const THEMES = Me;
export const THEME_FONTS = { sans: Re, serif: ue, mono: Y };
export const THEME_IDS = THEMES.map((theme) => theme.id);
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${banner}${body}\n${footer}`, 'utf8');

console.log(`[extract-themes] 已写入 ${OUT}`);
console.log(`[extract-themes] 切片 ${start}–${end}（${end - start} 字符）`);
console.log(`[extract-themes] 主题 ${ids.length} 套：${names.join('、')}`);
